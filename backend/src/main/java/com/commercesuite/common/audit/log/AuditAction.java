package com.commercesuite.common.audit.log;

/** Canonical audit action vocabulary. New values must be appended (never re-ordered). */
public enum AuditAction {
    // Auth
    USER_REGISTERED, USER_LOGGED_IN, USER_LOGGED_OUT,
    PASSWORD_CHANGED, PASSWORD_RESET_REQUESTED, PASSWORD_RESET_COMPLETED,
    EMAIL_VERIFIED, REFRESH_TOKEN_REUSED,
    // Vendor / catalog
    VENDOR_APPROVED, VENDOR_REJECTED, VENDOR_SUSPENDED,
    PRODUCT_APPROVED, PRODUCT_REJECTED,
    // Inventory
    INVENTORY_ADJUSTED,
    // Orders / shipping / returns
    ORDER_CREATED, ORDER_CANCELLED, ORDER_SHIPPED, ORDER_DELIVERED,
    RETURN_REQUESTED, RETURN_APPROVED,
    // Refunds
    REFUND_APPROVED, REFUND_REJECTED, REFUND_PROCESSED,
    // Payments
    PAYMENT_CAPTURED, PAYMENT_FAILED, PAYMENT_REFUNDED, PAYMENT_FRAUD_SUSPECTED,
    // Settlement / payout
    SETTLEMENT_LOCKED, SETTLEMENT_RELEASED,
    PAYOUT_INITIATED, PAYOUT_COMPLETED, PAYOUT_FAILED,
    // Notifications
    NOTIFICATION_FAILED,
    // Misc / governance
    SECURITY_VIOLATION, ADMIN_OVERRIDE
}